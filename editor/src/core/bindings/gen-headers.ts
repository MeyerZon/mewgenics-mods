// Generates the native layer's per-build headers from bindings/*.json:
//   native/framework/src/signatures.h  one SymbolSig table + one BuildInfo row per manifest
//                                      (identity, vtables, type id, data RVAs, FW_LK hook RVAs)
//   native/framework/src/offsets.h     OFF_* struct offsets and VT_* slot constants
// Offsets are plain #defines shared by status_engine.c and mewtest.c, so every manifest in the
// set must agree on them; a disagreement is a GenError (ship one DLL per build in that case).
// Pure: returns text; tools/bindings/gen-headers.ts writes the files. The golden test in
// editor/test/bindings-tests.ts fails when the committed headers are stale.

import { createHash } from "node:crypto";
import { symbolTable, dataTable, lkTable, entry } from "./manifest.ts";
import type { Manifest, Entry, EnumExposure, TableExposure, FieldExposure, MacroExposure } from "./manifest.ts";

export const HEADER_PATHS = Object.freeze({
  signatures: "native/framework/src/signatures.h",
  offsets: "native/framework/src/offsets.h",
});

/** BuildInfo scalar fields, in struct order, with the manifest exposure.field that supplies each. */
const BUILD_FIELDS = ["rva_LuckUp_vftable", "rva_Status_vftable", "rva_DefaultStatusSource", "luckUpTypeId", "rva_TacticsTest_vftable"];

export class GenError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "GenError";
  }
}

function banner(manifests: Manifest[]): string {
  const ids = manifests.map((m) => `bindings/${m.build.steamBuildId}.json`).join(", ");
  const sha = createHash("sha256").update(manifests.map((m) => JSON.stringify(m)).join("\n")).digest("hex").slice(0, 16);
  return `/* GENERATED by tools/bindings/gen-headers.ts from ${ids} (manifest digest ${sha}).\n` +
    ` * Do not edit: change the manifest and run \`npm run bindings:gen\` in editor/. The golden test in\n` +
    ` * editor/test/bindings-tests.ts fails while this file is stale. */\n`;
}

const u32 = (s: string, width = 0): string => "0x" + parseInt(s, 16).toString(16).padStart(width, "0") + "u";

/** the enum exposure of an entry (the tables above guarantee one exists) */
const enumExposure = (e: Entry): EnumExposure => e.exposure.find((x) => (x as EnumExposure).enum) as EnumExposure;

function fieldEntry(m: Manifest, field: string): Entry {
  const e = m.entries.find((x) => x.exposure.some((ex) => (ex as FieldExposure).field === field));
  if (!e) throw new GenError(`build ${m.build.steamBuildId}: no entry exposes BuildInfo field ${field}`);
  return e;
}

export function genSignaturesH(manifests: Manifest[]): string {
  if (manifests.length === 0) throw new GenError("no manifests");
  const lkCount = lkTable(manifests[0]).length;
  const symCount = symbolTable(manifests[0]).length;
  const dataCount = dataTable(manifests[0]).length;
  for (const m of manifests) {
    if (lkTable(m).length !== lkCount) throw new GenError(`build ${m.build.steamBuildId}: FW_LK has ${lkTable(m).length} entries, expected ${lkCount}`);
    if (symbolTable(m).length !== symCount) throw new GenError(`build ${m.build.steamBuildId}: FwSymbol has ${symbolTable(m).length} entries, expected ${symCount}`);
    if (dataTable(m).length !== dataCount) throw new GenError(`build ${m.build.steamBuildId}: FwData has ${dataTable(m).length} entries, expected ${dataCount}`);
  }
  const out: string[] = [];
  out.push(banner(manifests));
  out.push(`#pragma once
#include <stdint.h>
#include <stddef.h>
#include "framework_api.h"

/* A build is identified by the main module's PE TimeDateStamp + SizeOfImage (fw_build.c). Each code
 * symbol is located at load time by a unique byte pattern in the executable sections; expectedRva is
 * the RVA on the authoring build (drift log only). A symbol whose pattern is NULL has no relocation-free
 * unique window on this build and is taken at expectedRva (the identity gate already passed). Data
 * addresses, vtables, the type id and the raw status-lookup hook RVAs cannot be pattern-scanned yet;
 * they live in BuildInfo and are sanity-checked at runtime before use. The FwSymbol / FwData enums are
 * public (framework_api.h) and append-only; the tables here follow their order. */

#define FW_LK_COUNT ${lkCount}   /* status-name lookups aliased by status_engine.c (shapes A-E) */

typedef struct SymbolSig { const char *name; const char *pattern; intptr_t offset; uintptr_t expectedRva; } SymbolSig;

typedef struct BuildInfo {
    const char *name;
    uint32_t timeDateStamp;            /* IMAGE_FILE_HEADER.TimeDateStamp */
    uint32_t sizeOfImage;              /* IMAGE_OPTIONAL_HEADER64.SizeOfImage */
    uint32_t rva_LuckUp_vftable;       /* glaiel::LuckUp::vftable */
    uint32_t rva_Status_vftable;       /* glaiel::Status::vftable */
    uint32_t rva_DefaultStatusSource;  /* default applier source when the caller passes null */
    uint32_t luckUpTypeId;             /* value returned by LuckUp vtable slot 1 */
    uint32_t rva_TacticsTest_vftable;  /* glaiel::TacticsTest::vftable (slot 19 = the glow engine's hook target) */
    uint32_t rva_data[FW_DATA_COUNT_]; /* FwData order */
    const SymbolSig *symbols;          /* FW_SYMBOL_COUNT_ entries, FwSymbol order */
    const uint32_t *lkRvas;            /* FW_LK_COUNT entries, status_engine lookup order */
} BuildInfo;
`);
  for (const m of manifests) {
    const id = m.build.steamBuildId;
    out.push(`/* ---- build ${id}: ${m.build.name} (exe sha256 ${m.build.exeSha256.slice(0, 12)}..., SDL ${m.build.sdlVersion}) ---- */`);
    out.push(`static const SymbolSig FW_SYMBOLS_${id}[FW_SYMBOL_COUNT_] = {`);
    for (const e of symbolTable(m)) {
      const ex = enumExposure(e);
      // no relocation-free unique window (e.g. LuckUp_ctor): the DLL uses expectedRva on the identified build
      if (!e.signature) { out.push(`    { "${e.name}", NULL, 0, ${u32(e.rva || "0x0")} },  /* ${ex.enum} (raw RVA: no signature on this build) */`); continue; }
      out.push(`    { "${e.name}", "${e.signature.pattern}", ${e.signature.offset}, ${u32(e.rva || "0x0")} },  /* ${ex.enum} */`);
    }
    out.push(`};`);
    out.push(`static const uint32_t FW_LK_RVAS_${id}[FW_LK_COUNT] = {`);
    for (const e of lkTable(m)) {
      const ex = e.exposure.find((x) => (x as TableExposure).table === "FW_LK") as TableExposure;
      out.push(`    ${u32(e.rva || "0x0")},  /* [${ex.index}] ${ex.shape} ${e.name}${e.signature ? "" : " (raw RVA: no signature on this build)"} */`);
    }
    out.push(`};\n`);
  }
  out.push(`static const BuildInfo FW_BUILDS[] = {`);
  for (const m of manifests) {
    const id = m.build.steamBuildId;
    const b = m.build;
    const fields = BUILD_FIELDS.map((f) => {
      const e = fieldEntry(m, f);
      return f === "luckUpTypeId" ? u32(e.value || "0x0") : u32(e.rva || "0x0", 8);
    });
    out.push(`    /* ${b.gameVersion}, Steam build ${id}${b.linked ? `, linked ${b.linked}` : ""} */`);
    out.push(`    { "${b.name}", ${u32(b.timeDateStamp, 8)}, ${u32(b.sizeOfImage, 8)}, ${fields.join(", ")},`);
    const data = dataTable(m);
    data.forEach((e, i) => {
      const ex = enumExposure(e);
      const open = i === 0 ? "      { " : "        ";
      const close = i === data.length - 1 ? " }," : ",";
      out.push(`${open}${u32(e.rva || "0x0", 8)}${close}  /* ${ex.enum} */`);
    });
    out.push(`      FW_SYMBOLS_${id}, FW_LK_RVAS_${id} },`);
  }
  out.push(`};
#define FW_BUILD_COUNT (sizeof(FW_BUILDS) / sizeof(FW_BUILDS[0]))
#define FW_SYMBOL_COUNT ((size_t)FW_SYMBOL_COUNT_)
`);
  return out.join("\n");
}

/** manifest value string -> C literal */
const cval = (v: string): string => (v.startsWith("-") ? `(${v})` : v);

export function genOffsetsH(manifests: Manifest[]): string {
  if (manifests.length === 0) throw new GenError("no manifests");
  const base = manifests[0];
  const rows: { macro: string; e: Entry }[] = [];
  for (const e of base.entries) {
    for (const x of e.exposure) {
      const macro = (x as MacroExposure).macro;
      if (macro) rows.push({ macro, e });
    }
  }
  // every manifest must agree on every macro value
  for (const m of manifests.slice(1)) {
    for (const { macro, e } of rows) {
      const other = entry(m, e.name);
      if (!other) throw new GenError(`${macro}: entry ${e.name} exists in build ${base.build.steamBuildId} but not in ${m.build.steamBuildId}`);
      if (other.value !== e.value) throw new GenError(`${macro} (${e.name}) differs: ${e.value} in build ${base.build.steamBuildId} vs ${other.value} in build ${m.build.steamBuildId}; offsets are shared #defines, ship one DLL per build or port the layout first`);
    }
  }
  const out: string[] = [];
  out.push(banner(manifests));
  out.push(`#pragma once

/* Struct offsets and vtable-slot constants used by status_engine.c (framework) and mewtest.c (harness).
 * These are plain #defines shared by every build listed in signatures.h: the generator refuses to emit
 * this file when two manifests disagree. Per-build values (signatures, data RVAs, hook RVAs) live in
 * BuildInfo instead. Offsets flagged "unanchored" in the manifest are reported, never guessed, by the
 * port step. */
`);
  const offsets = rows.filter((r) => r.e.kind === "offset");
  const consts = rows.filter((r) => r.e.kind !== "offset");
  const byStruct = new Map<string, typeof offsets>();
  for (const r of offsets) {
    const k = r.e.struct || "?";
    if (!byStruct.has(k)) byStruct.set(k, []);
    byStruct.get(k)?.push(r);
  }
  const width = Math.max(...rows.map((r) => r.macro.length)) + 1;
  for (const [struct, list] of byStruct) {
    out.push(`/* ${struct} */`);
    for (const { macro, e } of list) {
      const note = [e.name, e.ctype].filter(Boolean).join(": ") + (e.note ? `; ${e.note}` : "");
      out.push(`#define ${macro.padEnd(width)}${cval(e.value || "0")}   /* ${note} */`);
    }
  }
  if (consts.length) {
    out.push(`/* vtable slots and other layout constants */`);
    for (const { macro, e } of consts) {
      const note = e.name + (e.note ? `; ${e.note}` : "");
      out.push(`#define ${macro.padEnd(width)}${cval(e.value || "0")}   /* ${note} */`);
    }
  }
  out.push("");
  return out.join("\n");
}

/** repo-relative path -> header text */
export function generateHeaders(manifests: Manifest[]): Record<string, string> {
  return {
    [HEADER_PATHS.signatures]: genSignaturesH(manifests),
    [HEADER_PATHS.offsets]: genOffsetsH(manifests),
  };
}
